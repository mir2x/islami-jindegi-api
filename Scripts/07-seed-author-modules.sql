-- per-module author endpoints sort by content count instead of position.
--
-- Positions here were recovered by tracing each old author to its current row through the
-- CONTENT (old author foreign keys against the live content tables), not through names -- names
-- have been renamed, duplicated and mangled by zero-width and Unicode differences. All 439 old
-- authors traced, 1:1, with no old author's content split across two current rows.
--
-- Positions are renumbered 1..N per module, preserving the old relative order. Authors with no
-- old counterpart (content filed in the new admin after the migration) are appended after them,
-- marked below.
--
-- Run AFTER Scripts/06 and after the AddAuthorModules migration.
-- 437 rows across 5 modules.
